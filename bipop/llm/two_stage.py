def _normalize_plan_symbol(name: str) -> str:
    return name.lower().replace("-", "_")


def _bool_constant_value(expr: Any) -> bool:
    if not expr.is_bool_constant():
        raise ValueError(f"Expected boolean constant, got: {expr}")
    return bool(expr.bool_constant_value())


def _ground_fluent_combinations(problem: Any) -> Dict[Any, bool]:
    """Every grounded boolean fluent of the problem with its initial value."""
    em = problem.environment.expression_manager
    state: Dict[Any, bool] = {}
    for fluent in problem.fluents:
        if not fluent.type.is_bool_type():
            continue
        default = problem.fluents_defaults.get(fluent, em.FALSE())
        default_value = bool(default.bool_constant_value())
        object_groups = [list(problem.objects(param.type)) for param in fluent.signature]
        if not object_groups:
            state[em.FluentExp(fluent, tuple())] = default_value
            continue
        for args in product(*object_groups):
            state[em.FluentExp(fluent, tuple(em.ObjectExp(arg) for arg in args))] = default_value

    for fluent_exp, value in problem.initial_values.items():
        if fluent_exp.is_fluent_exp() and fluent_exp.fluent().type.is_bool_type():
            state[fluent_exp] = bool(value.bool_constant_value())
    return state


def _state_line_needed(problem: Any, fluent_exp: Any, value: bool) -> bool:
    """True if this fact is needed to recreate the achieved stage-1 state."""
    if value:
        return True
    fluent = fluent_exp.fluent()
    if fluent.name in PYTHON_DEFAULT_TRUE_FLUENTS:
        return True
    default = problem.fluents_defaults.get(fluent, problem.environment.expression_manager.FALSE())
    if _bool_constant_value(default):
        return True
    explicit_initial = problem.explicit_initial_values.get(fluent_exp)
    return explicit_initial is not None and _bool_constant_value(explicit_initial)


def _safe_code_name(object_name: str, used_names: set[str]) -> str:
    base = re.sub(r"\W", "_", object_name)
    if not base or base[0].isdigit() or keyword.iskeyword(base):
        base = f"obj_{base}"
    candidate = base
    suffix = 2
    while candidate in used_names:
        candidate = f"{base}_{suffix}"
        suffix += 1
    used_names.add(candidate)
    return candidate


def _object_code_names(py_path: str, problem: Any) -> Dict[str, str]:
    """Python variable name of every object, reusing the names of the generated script."""
    normalized_object_names = {_normalize_plan_symbol(obj.name): obj.name for obj in problem.all_objects}
    code_names: Dict[str, str] = {}
    used_names: set[str] = set()

    source = Path(py_path).read_text(encoding="utf-8", errors="ignore")
    for line in source.splitlines():
        matched = OBJECT_ASSIGNMENT_RE.match(line)
        if not matched:
            continue
        var_name, object_name = matched.groups()
        actual_object_name = normalized_object_names.get(_normalize_plan_symbol(object_name))
        if actual_object_name is None or var_name in RESERVED_CODE_NAMES or keyword.iskeyword(var_name):
            continue
        if actual_object_name not in code_names or var_name == object_name:
            code_names[actual_object_name] = var_name
            used_names.add(var_name)

    for obj in sorted(problem.all_objects, key=lambda item: item.name):
        if obj.name not in code_names:
            code_names[obj.name] = _safe_code_name(obj.name, used_names)
    return code_names


def _format_fluent_call(fluent_exp: Any, object_code_names: Dict[str, str]) -> str:
    fluent = fluent_exp.fluent()
    # The fluent is called "above" in PDDL but object_above_object in the Python code.
    code_fluent_name = "object_above_object" if fluent.name == "above" else fluent.name
    args = ", ".join(object_code_names.get(arg.object().name, arg.object().name) for arg in fluent_exp.args)
    return f"{code_fluent_name}({args})" if args else f"{code_fluent_name}()"


def _stage2_object_init_lines(problem: Any, object_code_names: Dict[str, str]) -> List[str]:
    lines = ["# Objects carried over from the VAL-valid stage-1 problem."]
    grouped: Dict[str, List[str]] = {}
    addable_vars: List[str] = []

    for obj in sorted(problem.all_objects, key=lambda item: (item.type.name, item.name)):
        type_name = obj.type.name
        var_name = object_code_names.get(obj.name, obj.name)
        grouped.setdefault(type_name, []).append(var_name)
        if obj.name not in DOMAIN_DEFINED_OBJECTS:
            lines.append(f'{var_name} = Object("{obj.name}", {type_name})')
        if obj.name not in PROBLEM_INITIALIZED_OBJECTS:
            addable_vars.append(var_name)

    for type_name, list_name in (("obj_type", "objs"), ("point_type", "points")):
        lines.append(f"{list_name} = [{', '.join(grouped.get(type_name, []))}]")

    if addable_vars:
        lines.append(f"problem.add_objects([{', '.join(addable_vars)}])")
    return lines


def _time_triggered_plan_from_tfd(problem: Any, plan_text: str) -> TimeTriggeredPlan:
    actions = {_normalize_plan_symbol(action.name): action for action in problem.actions}
    objects = {_normalize_plan_symbol(obj.name): obj for obj in problem.all_objects}

    plan_steps = parse_tfd_temporal_plan(plan_text)
    if not plan_steps:
        raise ValueError("The selected stage-1 plan contains no temporal actions to simulate")

    timed_actions = []
    for step in plan_steps:
        action = actions.get(_normalize_plan_symbol(step["name"]))
        if action is None:
            raise ValueError(f"Plan action '{step['name']}' is not present in the generated problem")
        if len(step["args"]) != len(action.parameters):
            raise ValueError(f"Plan action '{step['name']}' has unexpected argument count")

        actual_parameters = []
        for raw_arg in step["args"]:
            obj = objects.get(_normalize_plan_symbol(raw_arg))
            if obj is None:
                raise ValueError(f"Plan object '{raw_arg}' is not present in the generated problem")
            actual_parameters.append(obj)
        timed_actions.append((step["start"], ActionInstance(action, actual_parameters), step["duration"]))

    return TimeTriggeredPlan(timed_actions, environment=problem.environment)


def _simulate_plan_final_state(problem: Any, plan_text: str) -> tuple[Any, int, int]:
    plan = _time_triggered_plan_from_tfd(problem, plan_text)
    validation = TimeTriggeredPlanValidator().validate(problem, plan)
    if validation.status != ValidationResultStatus.VALID:
        reason = validation.reason.name if validation.reason is not None else "unknown"
        raise ValueError(f"Unified Planning rejected the VAL-selected stage-1 plan: {reason}")
    if not validation.trace:
        raise ValueError("Unified Planning did not return a simulation trace for the stage-1 plan")

    if isinstance(validation.trace, dict):
        final_state = validation.trace[max(validation.trace)]
    else:
        final_state = validation.trace[-1]
    return final_state, len(plan.timed_actions), len(validation.trace)


def _state_bool_value(state: Any, fluent_exp: Any) -> bool:
    value = state.get_value(fluent_exp)
    if not value.is_bool_constant():
        raise ValueError(f"Expected boolean simulator value for {fluent_exp}, got: {value}")
    return bool(value.bool_constant_value())


def extract_stage1_state_context(
    py_path: str,
    domain_path: str,
    problem_path: str,
    plan_text: str,
) -> Dict[str, Any]:
    """Simulate the stage-1 plan and write its final state as stage-2 initialization code.

    Returns ``state_lines`` (``problem.set_initial_value(...)`` lines),
    ``object_init_lines`` and the combined ``injected_init_code``.
    """
    problem = PDDLReader().parse_problem(domain_path, problem_path)
    object_code_names = _object_code_names(py_path, problem)
    final_state, simulated_actions, trace_size = _simulate_plan_final_state(problem, plan_text)

    lines: List[str] = []
    for fluent_exp in sorted(_ground_fluent_combinations(problem), key=str):
        if fluent_exp.fluent().name not in STATE_TRANSFER_FLUENTS:
            continue
        value = _state_bool_value(final_state, fluent_exp)
        if not _state_line_needed(problem, fluent_exp, value):
            continue
        lines.append(f"problem.set_initial_value({_format_fluent_call(fluent_exp, object_code_names)}, {value})")

    debug_print(
        f"[STATE] simulated VAL-valid stage1 plan with Unified Planning: "
        f"actions={simulated_actions} trace_states={trace_size} exported_facts={len(lines)}",
        flush=True,
    )

    object_init_lines = _stage2_object_init_lines(problem, object_code_names)
    injected_init_code = "\n".join(
        object_init_lines
        + ["", "# Initial values injected from the VAL-valid achieved state after stage 1.", *lines]
    )
    return {
        "state_lines": lines,
        "object_init_lines": object_init_lines,
        "injected_init_code": injected_init_code,
    }


