"""Goal decomposition of BiPOP (``divide_goal``).

The full UP code generated by the LLM is split into two planning problems:

* stage 1 keeps the initial state and only the ``object_at_point(...)`` goals;
* stage 2 starts from the state stage 1's VAL-valid plan reaches (simulated
  with Unified Planning) and has all final goals.

The two stage plans are concatenated into one temporal plan.
Only StackBlock uses the two-stage pipeline (``TWO_STAGE_TASKS``).
"""

from __future__ import annotations

import ast
import keyword
import re
from fractions import Fraction
from itertools import product
from pathlib import Path
from typing import Any, Dict, List

from unified_planning.engines import TimeTriggeredPlanValidator
from unified_planning.engines.results import ValidationResultStatus
from unified_planning.io import PDDLReader
from unified_planning.plans import ActionInstance, TimeTriggeredPlan

from ..plan_format import combined_plan_offset, parse_tfd_temporal_plan
from .log import debug_print
from .planner import format_best_valid_preset

# Tasks whose goals are split into two stages; all other tasks are planned in one stage.
TWO_STAGE_TASKS = ("StackBlock",)


def uses_two_stage(task_name: str, divide_goal: bool = True) -> bool:
    """True if the two-stage pipeline runs for this task (``--no-divide_goal`` turns it off)."""
    return bool(divide_goal) and task_name in TWO_STAGE_TASKS

OBJECT_ASSIGNMENT_RE = re.compile(r"""^\s*([A-Za-z_]\w*)\s*=\s*Object\(\s*["']([^"']+)["']""")

# Fluents whose values are carried from the end of stage 1 into stage 2.
STATE_TRANSFER_FLUENTS = frozenset(
    (
        "arm_at",
        "arm_access",
        "available",
        "arm_free",
        "lifting",
        "object_at_area",
        "object_at_point",
        "object_on_object",
        "above",
        "water_in_cup",
        "clear",
        "on_table",
        "is_accessible",
        "is_releasable",
        "is_graspable",
        "point_at",
        "static",
    )
)

# PDDLReader loses the Python-side default_initial_value=True declarations of
# problem_initialization, so these are always written explicitly for stage 2.
PYTHON_DEFAULT_TRUE_FLUENTS = frozenset(
    ("is_releasable", "is_accessible", "clear", "arm_free", "on_table", "static")
)

# Objects that domain_definition already declares.
DOMAIN_DEFINED_OBJECTS = frozenset(
    ("left_area", "right_area", "overlap_area", "left_arm", "right_arm", "overlap_point_1", "overlap_point_2")
)
# Objects that problem_initialization already adds to the problem.
PROBLEM_INITIALIZED_OBJECTS = frozenset(("left_area", "right_area", "overlap_area", "left_arm", "right_arm"))
# Variable names used inside the action blocks; never reuse them for objects.
RESERVED_CODE_NAMES = frozenset(("aa", "pp", "oo", "p", "x", "y", "z", "w"))


# ---------------------------------------------------------------------------
# Splitting the full code string
# ---------------------------------------------------------------------------

def _is_problem_method_call(node: ast.AST, method_name: str) -> bool:
    return (
        isinstance(node, ast.Call)
        and isinstance(node.func, ast.Attribute)
        and node.func.attr == method_name
        and isinstance(node.func.value, ast.Name)
        and node.func.value.id == "problem"
    )


def _is_object_at_point_goal(node: ast.AST) -> bool:
    if not _is_problem_method_call(node, "add_goal") or not node.args:
        return False
    return any(
        isinstance(child, ast.Call) and isinstance(child.func, ast.Name) and child.func.id == "object_at_point"
        for child in ast.walk(node.args[0])
    )


def _source_segment(source: str, lines: List[str], node: ast.AST) -> str:
    segment = ast.get_source_segment(source, node)
    if segment is not None:
        return segment.strip()
    start = getattr(node, "lineno", 1)
    end = getattr(node, "end_lineno", start)
    return "\n".join(lines[start - 1 : end]).strip()


def goal_code_error(code_string: str, label: str) -> str | None:
    """Error message if goal-only code does more than add goals or overloads a point."""
    forbidden_patterns = {
        r"\bObject\s*\(": "define objects",
        r"problem\.add_objects\s*\(": "add objects",
        r"problem\.set_initial_value\s*\(": "set initial values",
        r"problem\.add_fluent\s*\(": "add fluents",
        r"\bProblem\s*\(": "create a new Problem",
        r"\bDurativeAction\s*\(": "define actions",
    }
    for pattern, description in forbidden_patterns.items():
        if re.search(pattern, code_string):
            return f"{label} must contain only problem.add_goal(...) lines; it must not {description}."

    goal_lines = [line.strip() for line in code_string.splitlines() if "problem.add_goal" in line]
    if not goal_lines:
        return f"{label} must contain at least one problem.add_goal(...) line."

    point_occupancy: Dict[str, str] = {}
    for line in goal_lines:
        matched = re.search(r"object_at_point\s*\(\s*([^,\s]+)\s*,\s*([^)]+?)\s*\)", line)
        if not matched:
            continue
        obj_name = matched.group(1).strip()
        point_name = matched.group(2).strip()
        existing_obj = point_occupancy.get(point_name)
        if existing_obj is not None and existing_obj != obj_name:
            return (
                f"{label} violates point occupancy: "
                f"{existing_obj} and {obj_name} are both assigned to {point_name}."
            )
        point_occupancy[point_name] = obj_name
    return None


def manual_split_full_code(code_string: str) -> Dict[str, Any]:
    """Split one full LLM code string into the stage-1 code and the stage-2 goal code.

    Raises ValueError when the code cannot be parsed or split.
    """
    lines = code_string.splitlines()
    try:
        tree = ast.parse(code_string)
    except SyntaxError as exc:
        raise ValueError(f"The generated Python code is not parseable: {exc}") from exc

    top_level_goal_nodes = [
        node
        for node in tree.body
        if isinstance(node, ast.Expr) and _is_problem_method_call(node.value, "add_goal")
    ]
    top_level_goal_ids = {id(node.value) for node in top_level_goal_nodes}
    nested_goal_lines = [
        getattr(node, "lineno", "?")
        for node in ast.walk(tree)
        if _is_problem_method_call(node, "add_goal") and id(node) not in top_level_goal_ids
    ]
    if nested_goal_lines:
        raise ValueError(
            "Final goals must be explicit top-level problem.add_goal(...) statements; "
            f"nested/generated goals were found at line(s): {nested_goal_lines}."
        )
    if not top_level_goal_nodes:
        raise ValueError("The full code string must include explicit final problem.add_goal(...) statements.")

    final_goal_lines = [_source_segment(code_string, lines, node) for node in top_level_goal_nodes]
    subgoal1_lines = [
        _source_segment(code_string, lines, node)
        for node in top_level_goal_nodes
        if _is_object_at_point_goal(node.value)
    ]
    if not subgoal1_lines:
        raise ValueError(
            "No object_at_point(...) final goals were found. The manual split needs "
            "object_at_point goals to derive subgoal1."
        )

    remove_lines: set[int] = set()
    for node in top_level_goal_nodes:
        start = getattr(node, "lineno", 1)
        end = getattr(node, "end_lineno", start)
        remove_lines.update(range(start, end + 1))

    setup_code = "\n".join(
        line for line_number, line in enumerate(lines, start=1) if line_number not in remove_lines
    ).rstrip()
    stage1_code = (
        setup_code
        + "\n\n# Manually derived subgoal1 from final object_at_point(...) goals.\n"
        + "\n".join(subgoal1_lines)
        + "\n"
    )
    stage2_goal_code = (
        "# Manually derived subgoal2: original final goals from the full code string.\n"
        + "\n".join(final_goal_lines)
        + "\n"
    )

    stage1_error = goal_code_error("\n".join(subgoal1_lines), "subgoal1")
    if stage1_error:
        raise ValueError(stage1_error)
    stage2_error = goal_code_error(stage2_goal_code, "subgoal2")
    if stage2_error:
        raise ValueError(stage2_error)

    return {
        "setup_code": setup_code,
        "stage1_code": stage1_code,
        "stage2_goal_code": stage2_goal_code,
        "final_goal_lines": final_goal_lines,
        "subgoal1_lines": subgoal1_lines,
    }


def compose_stage2_code(injected_init_code: str, goal_code: str) -> str:
    return (
        injected_init_code.strip()
        + "\n\n# Final goals manually extracted from the full code string.\n"
        + goal_code.strip()
        + "\n"
    )


