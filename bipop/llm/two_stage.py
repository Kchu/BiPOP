def _fraction_json(value: Fraction) -> Dict[str, Any]:
    return {"value": float(value), "exact": str(value)}


def _plan_steps_json(plan_text: str, stage: str, offset: Fraction = Fraction(0)) -> List[Dict[str, Any]]:
    steps: List[Dict[str, Any]] = []
    for step_index, step in enumerate(parse_tfd_temporal_plan(plan_text)):
        start = step["start"] + offset
        duration = step["duration"]
        steps.append(
            {
                "stage": stage,
                "stage_index": step_index,
                "start": _fraction_json(start),
                "duration": _fraction_json(duration),
                "end": _fraction_json(start + duration),
                "action": step["name"],
                "args": step["args"],
                "plan_line": (
                    f"{float(start):.6f}: ({' '.join([step['name'], *step['args']])}) [{float(duration):.6f}]"
                ),
            }
        )
    return steps


def _stage_summary(result: Dict[str, Any], actions: List[Dict[str, Any]]) -> Dict[str, Any]:
    return {
        "plan_path": result.get("plan_path"),
        "best_preset": result.get("val", {}).get("best_preset"),
        "best_valid_preset": format_best_valid_preset(result.get("best_valid_preset")),
        "makespan": result.get("makespan"),
        "plan_length": result.get("plan_length"),
        "planner_time_cost": result.get("planner_time_cost", 0.0),
        "actions": actions,
    }


def combined_plan_json_payload(
    task_name: str,
    index: int,
    result_1: Dict[str, Any],
    result_2: Dict[str, Any],
    final_plan_text: str,
) -> Dict[str, Any]:
    """JSON record of a combined two-stage plan with exact action timings."""
    offset = combined_plan_offset(result_1["plan_text"])
    stage1_steps = _plan_steps_json(result_1["plan_text"], "stage1")
    stage2_steps = _plan_steps_json(result_2["plan_text"], "stage2", offset)
    combined_steps = stage1_steps + stage2_steps
    combined_makespan = max((Fraction(step["end"]["exact"]) for step in combined_steps), default=Fraction(0))

    stage2 = _stage_summary(result_2, stage2_steps)
    stage2["offset_from_stage1"] = _fraction_json(offset)
    stage2["actions"] = stage2.pop("actions")  # keep "actions" as the last key
    return {
        "task_name": task_name,
        "index": index,
        "stage1": _stage_summary(result_1, stage1_steps),
        "stage2": stage2,
        "combined": {
            "makespan": _fraction_json(combined_makespan),
            "plan_length": len(combined_steps),
            "planner_time_cost": result_1.get("planner_time_cost", 0.0) + result_2.get("planner_time_cost", 0.0),
            "actions": combined_steps,
            "plan_text": final_plan_text,
        },
    }
